TS_BASE = {"int": "number", "string": "string", "bool": "boolean", "number": "number", "rect": "Rect",
           "object": "Record<string, unknown>"}


def ts_type(text):
    base, array, optional = parse_type(text)
    out = TS_BASE[base]
    if array:
        out = f"{out}[]"
    return f"{out} | null" if optional else out


def ts_arg_type(arg):
    if arg["type"] == "enum":
        return arg["enum"]
    return {"string": "string", "int": "number", "number": "number", "bool": "boolean",
            "string[]": "string[]"}[arg["type"]]


def ts_client(schema, enums):
    out = [f"// {NOTICE}", "", 'import net from "node:net";', 'import os from "node:os";', "",
           f"export const PROTOCOL = {schema['protocol']};", ""]
    for choices, name in enums.by_choices.items():
        out.append(f"export type {name} = {' | '.join(json.dumps(choice) for choice in choices)};")
    out += ["", "export interface Rect {", "  x: number;", "  y: number;", "  width: number;", "  height: number;", "}"]
    for command in generated(schema):
        kind, name, fields = result_info(command)
        if name:
            out += ["", f"export interface {name} {{"]
            out += [f"  {field['name']}: {ts_type(field['type'])};" for field in fields]
            out.append("}")
    names = []
    for event in schema["events"]:
        name = event_type(event["name"])
        out += ["", f"export interface {name}Data {{"]
        out += [f"  {field['name']}: {ts_type(field['type'])};" for field in event["data"]]
        out.append("}")
        names.append(f'{{ event: {json.dumps(event["name"])}; data: {name}Data }}')
    out += ["", "export type CatWMEvent =", "  | " + "\n  | ".join(names) + ";",
            f"export const EVENTS = {json.dumps([e['name'] for e in schema['events']])} as const;", "", TS_TRANSPORT]
    for command in generated(schema):
        kind, name, fields = result_info(command)
        returns = {"none": "void", "text": "string", "value": "unknown", "object": name,
                   "list": f"{name}[]"}[kind]
        args = sorted(command["args"], key=lambda arg: not arg["required"])
        params = ", ".join(f"{camel(arg['name'])}{'' if arg['required'] else '?'}: {ts_arg_type(arg)}" for arg in args)
        body = ", ".join(f"{json.dumps(arg['name'])}: {camel(arg['name'])}" for arg in args)
        call = f"this.call({json.dumps(command['name'])}, {{ {body} }})" if args else \
            f"this.call({json.dumps(command['name'])})"
        out += ["", f"  /** {command['summary']} */",
                f"  async {camel(command['name'])}({params}): Promise<{returns}> {{",
                f"    {'await ' + call + ';' if kind == 'none' else 'return (await ' + call + ') as ' + returns + ';'}",
                "  }"]
    out += ["}", ""]
    return "\n".join(out)


TS_TRANSPORT = '''export class CatWMError extends Error {
  constructor(readonly code: string, message: string) {
    super(message);
    this.name = "CatWMError";
  }
}

type Listener = (event: CatWMEvent) => void;

export interface PluginWindow {
  id: number;
  app: string | null;
  title: string | null;
}

export interface Invocation {
  arg: string;
  window: PluginWindow | null;
}

type Handler = (call: Invocation) => void | Promise<void>;

export function defaultPath(): string {
  const instance = process.env.CATWM_INSTANCE;
  const folder = instance === undefined ? ".config/catwm" : `.config/catwm/instances/${instance}`;
  return process.env.CATWM_SOCKET ?? `${os.homedir()}/${folder}/catwm.sock`;
}

export class CatWM {
  private nextId = 1;
  private buffer = "";
  private pending = new Map<number, { resolve: (value: unknown) => void; reject: (error: Error) => void }>();
  private listeners = new Set<Listener>();
  private handlers = new Map<string, Handler>();
  private ready: Promise<void>;
  hello: Record<string, unknown> = {};

  private constructor(private readonly socket: net.Socket) {
    this.ready = new Promise((resolve) => (this.onHello = resolve));
    socket.setEncoding("utf8");
    socket.on("data", (chunk: string) => this.receive(chunk));
    socket.on("close", () => this.fail(new CatWMError("closed", "CatWM closed the connection")));
    socket.on("error", (error) => this.fail(new CatWMError("failed", error.message)));
  }

  private onHello: () => void = () => undefined;

  static connect(path: string = defaultPath()): Promise<CatWM> {
    return new Promise((resolve, reject) => {
      const socket = net.createConnection(path);
      socket.once("error", (error) => reject(new CatWMError("not_running", `CatWM is not running: ${error.message}`)));
      socket.once("connect", async () => {
        socket.removeAllListeners("error");
        const client = new CatWM(socket);
        await client.ready;
        resolve(client);
      });
    });
  }

  close(): void {
    this.socket.end();
  }

  /** Run any command by name. */
  call(command: string, args: Record<string, unknown> = {}): Promise<unknown> {
    const id = this.nextId++;
    const clean = Object.fromEntries(Object.entries(args).filter(([, value]) => value !== undefined));
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.socket.write(JSON.stringify({ id, command, args: clean }) + "\\n");
    });
  }

  /**
   * Register a namespaced dispatcher, such as "myapp.toggle". CatWM sends each run of it to this connection
   * and doesn't wait for the handler. The name goes away when the connection closes.
   */
  async register(name: string, handler: Handler): Promise<string> {
    const registered = ((await this.call("register", { name })) as { name: string }).name;
    this.handlers.set(registered, handler);
    return registered;
  }

  /** Remove a dispatcher that this connection registered. */
  async unregister(name: string): Promise<void> {
    await this.call("unregister", { name });
    this.handlers.delete(name.toLowerCase());
  }

  /** Call the listener for each event this connection receives. Subscribe to events first. */
  onEvent(listener: Listener): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  /** Subscribe and yield events until the connection closes. */
  async *events(...names: (typeof EVENTS)[number][]): AsyncGenerator<CatWMEvent> {
    const queue: CatWMEvent[] = [];
    let wake: (() => void) | undefined;
    let closed = false;
    const off = this.onEvent((event) => {
      queue.push(event);
      wake?.();
    });
    this.socket.once("close", () => {
      closed = true;
      wake?.();
    });
    await this.subscribe(names);
    try {
      while (true) {
        const next = queue.shift();
        if (next) yield next;
        else if (closed) return;
        else await new Promise<void>((resolve) => (wake = resolve));
      }
    } finally {
      off();
    }
  }

  private receive(chunk: string): void {
    this.buffer += chunk;
    let newline: number;
    while ((newline = this.buffer.indexOf("\\n")) >= 0) {
      const line = this.buffer.slice(0, newline);
      this.buffer = this.buffer.slice(newline + 1);
      if (line) this.handle(JSON.parse(line));
    }
  }

  private handle(message: any): void {
    if (message.hello) {
      this.hello = message.hello;
      this.onHello();
    } else if (message.invoke) {
      void this.handlers.get(message.invoke)?.(message.data as Invocation);
    } else if (message.event) {
      this.listeners.forEach((listener) => listener(message as CatWMEvent));
    } else if (this.pending.has(message.id)) {
      const { resolve, reject } = this.pending.get(message.id)!;
      this.pending.delete(message.id);
      if (message.ok) resolve(message.result);
      else reject(new CatWMError(message.error?.code ?? "failed", message.error?.message ?? "The command failed"));
    }
  }

  private fail(error: Error): void {
    this.pending.forEach(({ reject }) => reject(error));
    this.pending.clear();
  }
'''


