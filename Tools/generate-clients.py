ROOT = Path(__file__).resolve().parent.parent
CLIENTS = ROOT / "Clients"
SCHEMA = json.loads((CLIENTS / "schema.json").read_text())
NOTICE = "Generated by Tools/generate-clients.py from Clients/schema.json. Do not edit."
SWIFT_KEYWORDS = {"default", "class", "protocol", "extension", "func", "in", "is", "as", "operator", "init", "self"}


# `register` and `unregister` need a handler table and a read loop, so each transport writes them by hand.
HAND_WRITTEN = {"register", "unregister"}


def generated(schema):
    return [command for command in schema["commands"] if command["name"] not in HAND_WRITTEN]


def words(name):
    return [part for part in re.split(r"[.\-_]", name) if part]


def snake(name):
    return "_".join(words(name))


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in words(name))


def camel(name):
    text = pascal(name)
    return text[:1].lower() + text[1:]


def event_type(name):
    return pascal(name)


def parse_type(text):
    optional = text.endswith("?")
    text = text.rstrip("?")
    array = text.endswith("[]")
    return text[:-2] if array else text, array, optional


class Enums:
    """One name for each distinct set of choices."""

    def __init__(self):
        self.by_choices = {}
        self.names = set()

    def name_for(self, command, arg):
        key = tuple(arg["choices"])
        if key not in self.by_choices:
            name = pascal(arg["name"])
            if name in self.names:
                name = pascal(command["name"]) + name
            self.names.add(name)
            self.by_choices[key] = name
        return self.by_choices[key]


def collect(schema):
    enums = Enums()
    for command in schema["commands"]:
        for arg in command["args"]:
            if arg["type"] == "enum":
                arg["enum"] = enums.name_for(command, arg)
    return enums


def result_info(command):
    result = command["result"]
    kind = result["kind"]
    base = pascal(command["name"])
    if kind == "object":
        return kind, base + "Result", result["fields"]
    if kind == "list":
        return kind, base + "Item", result["fields"]
    return kind, None, []


def doc(text):
    return text.replace('"""', "'''")


# ---------------------------------------------------------------- Python

PY_BASE = {"int": "int", "string": "str", "bool": "bool", "number": "float", "rect": "Rect",
           "object": "dict[str, Any]"}


def py_type(text):
    base, array, optional = parse_type(text)
    out = PY_BASE[base]
    if array:
        out = f"list[{out}]"
    return f"{out} | None" if optional else out


def py_arg_type(arg):
    if arg["type"] == "enum":
        return arg["enum"]
    return {"string": "str", "int": "int", "number": "float", "bool": "bool", "string[]": "list[str]"}[arg["type"]]


def py_client(schema, enums):
    out = [f'"""{NOTICE}"""', "from __future__ import annotations", "",
           "import json", "import os", "import socket", "import threading",
           "from typing import Any, Callable, Iterator, Literal, TypedDict", "",
           f"PROTOCOL = {schema['protocol']}", "",
           "", "class CatWMError(Exception):",
           "    def __init__(self, code: str, message: str):",
           "        super().__init__(message)",
           "        self.code = code",
           "        self.message = message", "", ""]
    for choices, name in enums.by_choices.items():
        out.append(f"{name} = Literal[{', '.join(json.dumps(choice) for choice in choices)}]")
    out += ["", "", "class Rect(TypedDict):", "    x: float", "    y: float", "    width: float", "    height: float", ""]
    for command in generated(schema):
        kind, name, fields = result_info(command)
        if name:
            out += ["", f"class {name}(TypedDict):"]
            out += [f"    {field['name']}: {py_type(field['type'])}" for field in fields] or ["    pass"]
            out.append("")
    event_names = []
    for event in schema["events"]:
        name = event_type(event["name"]) + "Data"
        out += ["", f"class {name}(TypedDict):"]
        out += [f"    {field['name']}: {py_type(field['type'])}" for field in event["data"]] or ["    pass"]
        out += ["", "", f"class {event_type(event['name'])}(TypedDict):",
                f"    event: Literal[{json.dumps(event['name'])}]", f"    data: {name}", ""]
        event_names.append(event_type(event["name"]))
    out += ["", "", "class PluginWindow(TypedDict):", "    id: int", "    app: str | None", "    title: str | None", "",
            "", "class Invocation(TypedDict):", "    arg: str", "    window: PluginWindow | None", "",
            f"Event = {' | '.join(event_names)}", f"EVENTS = {json.dumps([e['name'] for e in schema['events']])}",
            "", "", PY_TRANSPORT]
    for command in generated(schema):
        kind, name, fields = result_info(command)
        returns = {"none": "None", "text": "str", "value": "Any", "object": name,
                   "list": f"list[{name}]"}[kind]
        args = sorted(command["args"], key=lambda arg: not arg["required"])
        params = "".join(f", {snake(arg['name'])}: {py_arg_type(arg)}" + ("" if arg["required"] else " | None = None")
                         for arg in args)
        out += ["", f"    def {snake(command['name'])}(self{params}) -> {returns}:",
                f'        """{doc(command["summary"])}"""', "        args: dict[str, Any] = {}"]
        for arg in args:
            local = snake(arg["name"])
            line = f"        args[{json.dumps(arg['name'])}] = {local}"
            out += [line] if arg["required"] else [f"        if {local} is not None:", "    " + line]
        call = f"self.call({json.dumps(command['name'])}, args)"
        out.append(f"        return {call}" if kind != "none" else f"        {call}")
    return "\n".join(out) + "\n"


PY_TRANSPORT = '''def default_path() -> str:
    instance = os.environ.get("CATWM_INSTANCE")
    folder = "~/.config/catwm" if instance is None else f"~/.config/catwm/instances/{instance}"
    return os.environ.get("CATWM_SOCKET") or os.path.expanduser(f"{folder}/catwm.sock")


class CatWM:
    """A connection to the running CatWM app. Calls are safe to make from many threads."""

    def __init__(self, path: str | None = None, timeout: float | None = 10.0):
        self._socket = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self._socket.settimeout(timeout)
        try:
            self._socket.connect(path or default_path())
        except OSError as error:
            self._socket.close()
            raise CatWMError("not_running", f"CatWM is not running: {error}") from error
        self._reader = self._socket.makefile("r", encoding="utf-8", newline="\\n")
        self._lock = threading.RLock()
        self._next_id = 1
        self._handlers: dict[str, Callable[[Invocation], None]] = {}
        self.hello: dict[str, Any] = json.loads(self._reader.readline()).get("hello", {})

    def close(self) -> None:
        """Close the connection. This also wakes a thread that waits to read from it."""
        try:
            self._socket.shutdown(socket.SHUT_RDWR)
        except OSError:
            pass
        self._reader.close()
        self._socket.close()

    def __enter__(self) -> "CatWM":
        return self

    def __exit__(self, *exc: Any) -> None:
        self.close()

    def call(self, command: str, args: dict[str, Any] | None = None) -> Any:
        """Run any command by name. Events that arrive on this connection are dropped."""
        with self._lock:
            request_id = self._next_id
            self._next_id += 1
            line = json.dumps({"id": request_id, "command": command, "args": args or {}}) + "\\n"
            self._socket.sendall(line.encode("utf-8"))
            while True:
                text = self._reader.readline()
                if not text:
                    raise CatWMError("closed", "CatWM closed the connection")
                reply = json.loads(text)
                if reply.get("id") != request_id:
                    self._invoke(reply)
                    continue
                if reply.get("ok"):
                    return reply.get("result")
                error = reply.get("error") or {}
                raise CatWMError(error.get("code", "failed"), error.get("message", "The command failed"))

    def register(self, name: str, handler: Callable[[Invocation], None]) -> str:
        """Register a namespaced dispatcher, such as "myapp.toggle". CatWM sends each run of it to this connection.

        The handler runs while this connection reads: in `serve`, or while another call waits for its answer.
        CatWM never waits for the handler. The name goes away when the connection closes."""
        registered = self.call("register", {"name": name})["name"]
        self._handlers[registered] = handler
        return registered

    def unregister(self, name: str) -> None:
        """Remove a dispatcher that this connection registered."""
        self.call("unregister", {"name": name})
        self._handlers.pop(name.lower(), None)

    def serve(self) -> None:
        """Run the handlers of the registered dispatchers until the connection closes.

        Calls from other threads wait while this runs, so use a second connection for them."""
        with self._lock:
            self._socket.settimeout(None)
            while True:
                text = self._reader.readline()
                if not text:
                    return
                self._invoke(json.loads(text))

    def _invoke(self, message: dict[str, Any]) -> None:
        handler = self._handlers.get(message.get("invoke", ""))
        if handler:
            handler(message["data"])

    @staticmethod
    def events(*names: str, path: str | None = None) -> Iterator[Event]:
        """Yield events until the connection closes. This opens a connection of its own."""
        with CatWM(path, timeout=None) as client:
            client.call("subscribe", {"events": list(names)})
            while True:
                text = client._reader.readline()
                if not text:
                    return
                message = json.loads(text)
                if "event" in message:
                    yield message
'''


